def create_source(
    source_id: str,
    title: str,
    source_type: str,
    tier: str,
    authority: str,
    official_url: str,
    exact_document_url: str,
    jurisdiction: str = "Union of India",
    state: str = "All",
    district: str = "All",
    municipality: str = "All",
    act_number: str = "",
    act_year: str = "",
    language: str = "English",
    original_language: str = "English",
    legal_domains: str = "",
    legal_intents: str = "",
    published_date: str = "2024-01-01",
    effective_date: str = "2024-07-01",
    valid_from: str = "2024-07-01",
    valid_until: str = "Active",
    amendment_of: str = "",
    superseded_by: str = "",
    repealed_by: str = "",
    commencement_status: str = "COMMENCED",
    applicability_conditions: str = "Universal across applicable jurisdiction",
    licence_or_terms: str = "Official Gazette / Public Domain",
    format_: str = "PDF/HTML",
    document_version: str = "2026.1",
    last_fetched: str = "",
    last_verified: str = "",
    verification_status: str = "PENDING",
    ingestion_status: str = "UNVERIFIED",
    indexed_chunk_count: int = 0,
    embedding_model: str = "",
    embedding_version: str = "",
) -> Dict[str, Any]:
    # A metadata-derived value is not a content checksum. Leave it empty until
    # runtime verification hashes the actual fetched bytes.
    content_checksum = ""
    
    # Map backward-compatible status
    status_compat = commencement_status
    if commencement_status in ["REPEALED", "HISTORICAL"]:
        status_compat = "HISTORICAL"
    elif commencement_status in ["COMMENCED", "ENACTED", "PARTIALLY_COMMENCED"]:
        status_compat = "ACTIVE"
    elif commencement_status == "MODEL_LAW":
        status_compat = "ADVISORY_MODEL"

    return {
        "source_id": source_id,
        "document_id": f"DOC_{source_id}",
        "title": title,
        "name": title,
        "source_type": source_type,
        "tier": tier,
        "authority": authority,
        "official_url": official_url,
        "exact_document_url": exact_document_url,
        "url": exact_document_url or official_url,
        "jurisdiction": jurisdiction,
        "state": state,
        "district": district,
        "municipality": municipality,
        "act_number": act_number,
        "act_year": act_year,
        "language": language,
        "original_language": original_language,
        "legal_domains": legal_domains,
        "legal_intents": legal_intents,
        "published_date": published_date,
        "effective_date": effective_date,
        "valid_from": valid_from,
        "valid_until": valid_until,
        "amendment_of": amendment_of,
        "superseded_by": superseded_by,
        "repealed_by": repealed_by,
        "commencement_status": commencement_status,
        "status": status_compat,
        "applicability_conditions": applicability_conditions,
        "licence_or_terms": licence_or_terms,
        "format": format_,
        "content_checksum": content_checksum,
        "document_version": document_version,
        "last_fetched": last_fetched,
        "last_verified": last_verified,
        "verification_status": verification_status,
        "ingestion_status": ingestion_status,
        "indexed_chunk_count": indexed_chunk_count,
        "embedding_model": embedding_model,
        "embedding_version": embedding_version,
    }


