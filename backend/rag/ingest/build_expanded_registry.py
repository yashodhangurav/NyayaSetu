def write_expanded_registry_csv(output_path: str = "docs/source_registry.csv") -> int:
    sources = get_all_expanded_sources()
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=REGISTRY_COLUMNS)
        writer.writeheader()
        for s in sources:
            writer.writerow(s)
    return len(sources)


